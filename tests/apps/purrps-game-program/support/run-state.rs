// Exercise every maximum-size enum/Option combination, not valid gameplay.
pub fn max_layout() -> RunGameState {
    let key = Pubkey::new_from_array([1; 32]);
    let binding = VersionBinding {
        version: 1,
        content_hash: [1; 32],
    };
    let observation = OracleObservation {
        sequence: 1,
        price: 1,
        exponent: -8,
        published_at_seconds: 1,
        posted_slot: 1,
        content_hash: [1; 32],
    };
    let intent = AcceptedIntent {
        envelope: IntentEnvelope {
            protocol_version: 1,
            rules_version: 1,
            run: key,
            client_sequence: 1,
            action: PlayerIntent::Move {
                axis: InputAxis::Right,
            },
        },
        assigned_tick: 1,
        accepted_order: 1,
    };
    RunGameState {
        schema_version: 1,
        bump: 1,
        escrow: key,
        snapshot: RunSnapshot {
            protocol_version: 1,
            run: key,
            owner: key,
            nonce: 1,
            market: Market::Btc,
            stake_base_units: 1,
            max_gross_base_units: 10,
            rules_binding: binding,
            rules: RULES_V1,
            cat: CatSnapshot {
                definition: CATALOG_V1.cats[0],
                defining_catalog: binding,
                level: 1,
                stats: cat_stats(CatId::Collector, 1).unwrap(),
            },
            oracle: OracleBinding {
                program: key,
                account: key,
                write_authority: key,
                validator: key,
                feed_id: 1,
                schema_version: 3,
                max_age_seconds: 2,
                max_future_skew_seconds: 1,
                min_exponent: -8,
                max_exponent: -8,
            },
            input_permission: InputPermission {
                owner: key,
                input_key: key,
                program: key,
                session_token: key,
                expires_at_seconds: 1,
            },
            asset_manifest: binding,
            activation_deadline_seconds: 1,
            delegation_epoch: 1,
        },
        snapshot_hash: [1; 32],
        phase: RunPhase::TerminalRecorded,
        active_ticks: 1,
        world_origin_pixels: 1,
        runner: RunnerState {
            x_subpixels: 0,
            y_subpixels: 0,
            vx_subpixels_per_tick: 0,
            vy_subpixels_per_tick: 0,
            automatic_speed_subpixels_per_tick: 1024,
            grounded: true,
            axis: InputAxis::Neutral,
            dash_ends_at_tick: 1,
            dash_ready_at_tick: 1,
            shield_contact_ends_at_tick: 1,
        },
        entities: (0..MAX_WORLD_ENTITIES)
            .map(|id| WorldEntity {
                id: id as u64,
                kind: EntityKind::Booster(Power::Shield),
                x_subpixels: 0,
                y_subpixels: 0,
                width_subpixels: 1,
                height_subpixels: 1,
                designated_coin: Some(0),
                designated_checkpoint: 0,
                consumed: false,
            })
            .collect(),
        entity_count: MAX_WORLD_ENTITIES as u8,
        next_entity_id: 64,
        observations: vec![observation; MAX_RECENT_OBSERVATIONS],
        observation_head: 0,
        observation_count: MAX_RECENT_OBSERVATIONS as u8,
        start_observation: Some(observation),
        intents: vec![Some(intent); MAX_QUEUED_INTENTS],
        intent_head: 0,
        intent_count: MAX_QUEUED_INTENTS as u8,
        last_accepted_sequence: 1,
        last_processed_sequence: 1,
        last_accepted_order: 1,
        control_window_seconds: 1,
        control_updates_in_window: 1,
        last_heartbeat_tick: 1,
        inactive_exit_tick: Some(1),
        key_exit_tick: Some(1),
        input_key_revoked: false,
        score: 1,
        total_coins: 1,
        designated_coin_mask: 1,
        qualified_checkpoints: 1,
        powers: [PowerState {
            ready_at_tick: 1,
            ends_at_tick: 1,
            charges: 1,
        }; 4],
        crank: CrankState {
            task: key,
            cancel_authority: key,
            generation: 1,
            last_execution_ordinal: 1,
            trusted_elapsed_ms: 1,
            consumed_elapsed_ms: 1,
            completion_attempts: 1,
        },
        suspension: Some(Suspension {
            reason: FaultReason::UnsafeWorld,
            started_at_seconds: 1,
        }),
        terminal: Some(RunTerminal {
            reason: TerminalReason::TechnicalAbort,
            fault: Some(FaultReason::UnsafeWorld),
            active_ticks: 1,
            qualified_checkpoints: 1,
            score: 1,
            coins: 1,
            processed_sequence: 1,
            final_observation: Some(observation),
            gross_payout_base_units: 0,
            refund_base_units: 1,
        }),
    }
}
