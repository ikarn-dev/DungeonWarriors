import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../../", import.meta.url);
export const ENGINE_SOURCES = [
  "apps/web/lib/dungeon/rules.ts",
  "apps/web/lib/dungeon/warriors.ts",
  "apps/web/lib/dungeon/enemies.ts",
  "apps/web/lib/dungeon/random.ts",
  "apps/web/lib/dungeon/rooms.ts",
  "apps/web/lib/dungeon/generate.ts",
  "apps/web/lib/dungeon/simulation.ts",
  "apps/web/lib/dungeon/replay.ts",
  "apps/web/lib/dungeon/protocol.ts",
  "apps/web/lib/server/dungeon-randomness.ts",
  "apps/web/lib/server/dungeon-run.ts",
].sort();
export function engineHash(
  read = (path) => readFileSync(new URL(path, root), "utf8"),
) {
  const hash = createHash("sha256").update("purrps:dungeon-engine:v2\0");
  for (const path of ENGINE_SOURCES) {
    const source = read(path).replace(/\r\n/g, "\n");
    hash
      .update(path)
      .update("\0")
      .update(createHash("sha256").update(source).digest());
  }
  return hash.digest("hex");
}
export function checkEngine(write = false) {
  const hash = engineHash();
  const bytes = Array.from(Buffer.from(hash, "hex")).join(", ");
  const outputs = {
    "apps/web/lib/dungeon/engine-binding.ts": `// Generated by scripts/program/dungeon-engine.mjs; do not edit.\nexport const ENGINE_HASH = "${hash}";\n`,
    "apps/purrps-game-program/programs/purrps-game/src/dungeon_engine.rs": `// Generated by scripts/program/dungeon-engine.mjs; do not edit.\npub const DUNGEON_ENGINE_HASH: [u8; 32] = [\n    ${bytes},\n];\n`,
  };
  for (const [path, source] of Object.entries(outputs)) {
    const target = new URL(path, root);
    if (write) writeFileSync(target, source);
    else if (
      readFileSync(target, "utf8").replace(/\s/g, "") !==
      source.replace(/\s/g, "")
    )
      throw new Error(`STALE_DUNGEON_ENGINE_BINDING:${path}`);
  }
  return hash;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2];
  if (!["--check", "--write"].includes(mode) || process.argv.length !== 3)
    throw Error(
      "Usage: node scripts/program/dungeon-engine.mjs --check|--write",
    );
  process.stdout.write(`${checkEngine(mode === "--write")}\n`);
}
